function stripDiacritics(s: string): string {
  return s
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase();
}

export function searchWorldLanguages(query: string): WorldLanguageInfo[] {
  const q = stripDiacritics(query.trim());
  if (!q) return WORLD_LANGUAGES;
  return WORLD_LANGUAGES.filter((lang) => {
    const hay = stripDiacritics(
      `${lang.nativeName} ${lang.ptName} ${lang.enName} ${lang.code}`
    );
    return hay.includes(q);
  });
}
